// Bundles the game engine + the PvP referee/service into single ES modules (Anvil, Nov 2):
//   supabase/functions/match/engine.bundle.js   -> imported by the Deno Edge Function (same rules as the game, no second copy)
//   projects/oreheart-8/tools/.build/pvp-server.mjs -> imported by the local mock server (tools/pvp-mock-server.mjs) and the checks
// Usage (from projects/oreheart-8): node tools/bundle-engine.mjs
// The content JSON files are baked in, so the bundle must be rebuilt after a card/deck/rule change (the deploy workflow does it).
import { build } from 'esbuild';
import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '..');
const repo = resolve(app, '../..');
let sha = 'dev';
try { sha = execSync('git rev-parse --short HEAD', { cwd: repo, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { /* no git */ }

// one entry that re-exports everything the server side needs
const entry = resolve(app, 'tools/.build/server-entry.ts');
mkdirSync(dirname(entry), { recursive: true });
writeFileSync(entry, `export * from '../../src/server/service';
export * from '../../src/server/referee';
export { MemoryStore } from '../../src/server/memory-store';
export { legalActions, createMatch, applyAction, STARTER_DECK_LIST, STARTER_DECKS, COMMANDERS, CARDS, CONFIG } from '../../src/engine';
export { setDiceMode, getDiceMode } from '../../src/engine/dice';
export { mirror } from '../../src/engine/mirror';
export { presentFor, realAction } from '../../src/engine/view';
export const ENGINE_VERSION = ${JSON.stringify(sha)};
`);

const common = { entryPoints: [entry], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', sourcemap: false, logLevel: 'warning', mainFields: ['module', 'main'] };
await build({ ...common, outfile: resolve(repo, 'supabase/functions/match/engine.bundle.js'), banner: { js: '// GENERATED by projects/oreheart-8/tools/bundle-engine.mjs; do not edit. Engine ' + sha } });
await build({ ...common, outfile: resolve(app, 'tools/.build/pvp-server.mjs'), banner: { js: '// GENERATED by tools/bundle-engine.mjs; do not edit. Engine ' + sha } });
console.log('engine bundle', sha, '->', 'supabase/functions/match/engine.bundle.js', 'and', 'tools/.build/pvp-server.mjs');
